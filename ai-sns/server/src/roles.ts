/**
 * 質問・頼みごとへの返信の「役割分担」。
 * 相手が質問や頼みごとをしたとき、返信する全員が同じことを言うのではなく、
 * 1つの答えを分担して話す(要点を答える人、具体例を挙げる人、注意点を添える人、質問を返す人、共感する人)。
 * 返信は1回のAI呼び出しで全員分を作るので、役割を指定すれば、内容が重ならず、自然に分散する。
 */

/** 質問・頼みごと・相談をしているか(ルールベース。外れても、ふつうの返信になるだけ) */
export function looksLikeRequest(text: string): boolean {
  return /[?？]|かな[ぁあ〜]?\s*$|かなあ|かなぁ|だろう|でしょうか|ですか|教えて|おすすめ|オススメ|お勧め|知りたい|ないかな|あるかな|どうしたら|どうすれば|どれが|何が(いい|良い|おすすめ)|何を(すれば|したら)|どこが|いつが|どう(思う|かな)|してほしい|相談|困って|悩んで|わからない|分からない/.test(text);
}

export const ROLES = [
  { id: "answer", text: "相手の疑問・頼みごとに、要点を具体的に答える(調べた結果があれば、その内容を使う)" },
  { id: "pick", text: "自分の好みや経験から、具体的なものを1つ挙げて勧める(名前・場所・やり方など)" },
  { id: "supplement", text: "答えに、役に立つ補足や注意点・コツをひとつ添える" },
  { id: "ask", text: "相手の状況を知るための、短い質問をひとつだけ返す" },
  { id: "react", text: "軽い共感や感想をひと言。答えは他の人に任せる" },
] as const;

/**
 * 返信する人に役割を割り当てる。personaIds は「その話題に近い順」で渡す。
 * 先頭(いちばん近い人)が「答える」、次が「具体例」…の順。人数が役割より多ければ、残りは「共感」。
 * 1人だけなら、その人が「答える」。
 */
export function assignRoles(personaIds: string[]): Map<string, string> {
  const out = new Map<string, string>();
  personaIds.forEach((id, i) => out.set(id, (ROLES[i] ?? ROLES[ROLES.length - 1]!).text));
  return out;
}
